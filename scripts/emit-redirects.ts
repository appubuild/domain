/**
 * Emit static-hosting redirect rules after `next build`.
 *
 * A static export cannot redirect at request time — there is no server. So redirects that
 * an editor creates in the admin panel are compiled into host configuration files at build
 * time:
 *
 *   out/.htaccess    Apache (what most shared hosts run)
 *   out/_redirects   Netlify / Cloudflare Pages
 *   out/redirects.json  machine-readable audit copy
 *
 * Source of truth is the `redirects` table. When Supabase is not configured, or the fetch
 * fails, the script still writes the canonical-host and 404 rules, reports what happened,
 * and exits 0 — a build must not be silently shipped with *pretend* redirects, so the
 * outcome is printed loudly instead.
 */

import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

type RedirectRow = {
  source_path: string;
  target_path: string;
  status_code: number;
  enabled: boolean;
};

const OUT_DIR = path.resolve("out");
const RESERVED_PREFIXES = ["/_next", "/admin", "/api"];

async function loadDotEnv(): Promise<void> {
  for (const file of [".env.local", ".env"]) {
    try {
      const raw = await readFile(path.resolve(file), "utf8");
      for (const line of raw.split("\n")) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith("#")) continue;
        const eq = trimmed.indexOf("=");
        if (eq === -1) continue;
        const key = trimmed.slice(0, eq).trim();
        let value = trimmed.slice(eq + 1).trim();
        if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
          value = value.slice(1, -1);
        }
        if (!process.env[key]) process.env[key] = value;
      }
      return;
    } catch {
      // try the next candidate
    }
  }
}

async function fetchRedirects(): Promise<{ rows: RedirectRow[]; source: string; warning?: string }> {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
  if (!url || !key) {
    return {
      rows: [],
      source: "none",
      warning: "Supabase env vars are absent, so no database redirects were compiled.",
    };
  }

  const endpoint = `${url.replace(/\/$/, "")}/rest/v1/redirects?select=source_path,target_path,status_code,enabled&enabled=eq.true&order=source_path`;
  try {
    const response = await fetch(endpoint, {
      headers: { apikey: key, Authorization: `Bearer ${key}` },
    });
    if (!response.ok) {
      return {
        rows: [],
        source: "supabase",
        warning: `Redirect fetch returned HTTP ${response.status}; only the default rules were written.`,
      };
    }
    const rows = (await response.json()) as RedirectRow[];
    return { rows, source: "supabase" };
  } catch (error) {
    return {
      rows: [],
      source: "supabase",
      warning: `Redirect fetch failed (${(error as Error).message}); only the default rules were written.`,
    };
  }
}

function valid(rows: RedirectRow[]): RedirectRow[] {
  const seen = new Set<string>();
  const result: RedirectRow[] = [];
  for (const row of rows) {
    const source = row.source_path?.trim();
    const target = row.target_path?.trim();
    if (!source || !target) continue;
    if (!source.startsWith("/") || seen.has(source)) continue;
    if (RESERVED_PREFIXES.some((prefix) => source === prefix || source.startsWith(`${prefix}/`))) continue;
    if (!target.startsWith("/") && !target.startsWith("https://")) continue;
    if (target === source) continue;
    if (![301, 302, 307, 308].includes(Number(row.status_code))) continue;
    seen.add(source);
    result.push({ source_path: source, target_path: target, status_code: Number(row.status_code), enabled: true });
  }
  return result;
}

function apacheRules(rows: RedirectRow[], appUrl: string | null): string {
  const lines: string[] = [];
  lines.push("# Generated by scripts/emit-redirects.ts — edits here are overwritten on build.");
  lines.push("<IfModule mod_rewrite.c>");
  lines.push("  RewriteEngine On");

  if (appUrl && appUrl.startsWith("https://")) {
    // Canonical host: http -> https, apex -> www (or whatever the configured host is).
    const host = new URL(appUrl).host;
    lines.push("  # canonical host + protocol");
    lines.push("  RewriteCond %{HTTPS} off [OR]");
    lines.push(`  RewriteCond %{HTTP_HOST} !^${host.replace(/\./g, "\\.")}$ [NC]`);
    lines.push(`  RewriteRule ^ https://${host}%{REQUEST_URI} [R=301,L]`);
  }

  for (const row of rows) {
    const target = row.target_path.startsWith("http") ? row.target_path : row.target_path;
    const flag = row.status_code === 301 || row.status_code === 308 ? "R=301,L" : "R=302,L";
    lines.push(`  RewriteRule ^${row.source_path.replace(/^\//, "").replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}/?$ ${target} [${flag}]`);
  }

  lines.push("</IfModule>");
  lines.push("");
  lines.push("ErrorDocument 404 /404.html");
  lines.push("DirectoryIndex index.html");
  lines.push("Options -Indexes");
  return lines.join("\n") + "\n";
}

function netlifyRules(rows: RedirectRow[]): string {
  const header = "# Generated by scripts/emit-redirects.ts — edits here are overwritten on build.\n";
  if (rows.length === 0) return header;
  return header + rows.map((row) => `${row.source_path}  ${row.target_path}  ${row.status_code}`).join("\n") + "\n";
}

async function main() {
  await loadDotEnv();
  const { rows, source, warning } = await fetchRedirects();
  const redirects = valid(rows);
  const appUrl = process.env.NEXT_PUBLIC_APP_URL ?? null;

  await mkdir(OUT_DIR, { recursive: true });
  await writeFile(path.join(OUT_DIR, ".htaccess"), apacheRules(redirects, appUrl), "utf8");
  await writeFile(path.join(OUT_DIR, "_redirects"), netlifyRules(redirects), "utf8");
  await writeFile(
    path.join(OUT_DIR, "redirects.json"),
    JSON.stringify(
      {
        generatedAt: new Date().toISOString(),
        source,
        canonicalHost: appUrl ? new URL(appUrl).host : null,
        skippedForReservedRoutes: rows.length - redirects.length,
        redirects,
      },
      null,
      2,
    ) + "\n",
    "utf8",
  );

  if (warning) console.warn(`[redirects] ${warning}`);
  console.log(`[redirects] ${redirects.length} rule(s) compiled into out/.htaccess and out/_redirects (source: ${source}).`);
}

main().catch((error) => {
  console.error("[redirects] failed:", error);
  process.exitCode = 1;
});
