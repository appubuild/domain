/**
 * Generates api/database/seed.sql and the combined import file
 * api/database/safehomenetwork.sql from the frontend's real data.
 *
 *   npm run api:seed
 *
 * Why: the API must ship with exactly the same 5 categories, 15 services,
 * 10 phone groups and 20 numbers the website uses. Generating the seed from
 * src/config/services.ts and src/data/serviceNumbers.ts removes any chance of
 * transcription drift.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { build } from 'vite'

const root = process.cwd()

const q = (value) => {
  if (value === null || value === undefined || value === '') return 'NULL'
  if (typeof value === 'number') return String(value)
  if (typeof value === 'boolean') return value ? '1' : '0'
  return `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`
}

const json = (value) =>
  value === null || value === undefined ? 'NULL' : q(JSON.stringify(value))

const iso = (value) => {
  const date = value ? new Date(value) : new Date()
  if (Number.isNaN(date.getTime())) return q(new Date().toISOString().slice(0, 19).replace('T', ' '))
  return q(date.toISOString().slice(0, 19).replace('T', ' '))
}

const slugify = (value) =>
  String(value)
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')

/** Loads the real frontend data through Vite so TS path aliases resolve. */
const loadFrontendData = async () => {
  const entry = resolve(root, 'scripts/api-data-source.tsx')
  writeFileSync(
    entry,
    `import { SERVICES, SERVICE_CATEGORIES } from '@/config/services'
import { SITE } from '@/config/site'
import { SERVICE_PHONE_NUMBERS } from '@/data/serviceNumbers'
import { SERVICE_NUMBER_MAP, CALL_DIRECTORY_CATEGORIES } from '@/data/serviceNumberMapping'
import { HOME_FAQS, HOW_IT_WORKS_FAQS } from '@/config/faqs'
import { buildSeedWorkspace } from '@/admin/data/seed'

const seed = buildSeedWorkspace()

globalThis.__SHN_DATA__ = {
  site: SITE,
  categories: SERVICE_CATEGORIES,
  services: SERVICES,
  groups: SERVICE_PHONE_NUMBERS,
  mapping: SERVICE_NUMBER_MAP,
  directory: CALL_DIRECTORY_CATEGORIES,
  faqs: { home: HOME_FAQS, howItWorks: HOW_IT_WORKS_FAQS },
  pages: seed.pages,
  posts: seed.posts,
  sections: seed.sections,
  niches: seed.niches,
}
`,
  )

  await build({
    configFile: resolve(root, 'vite.config.ts'),
    logLevel: 'error',
    build: {
      ssr: entry,
      outDir: '.api-seed-build',
      emptyOutDir: true,
      write: true,
    },
  })

  const module = await import(resolve(root, '.api-seed-build/api-data-source.js'))
  void module
  return globalThis.__SHN_DATA__
}

const NICHE_BY_CATEGORY = {
  exterior: 'property-exterior',
  systems: 'home-systems',
  remodeling: 'remodeling',
  restoration: 'restoration-emergency',
  specialty: 'specialty-trades',
}

const buildSeed = (data) => {
  const lines = []
  const push = (line = '') => lines.push(line)

  push('-- ----------------------------------------------------------------------------')
  push('-- SEED — generated by `npm run api:seed` from the frontend source of truth.')
  push('-- Do not edit by hand; change src/config/services.ts or src/data/* and re-run.')
  push('-- ----------------------------------------------------------------------------')
  push('')
  push('SET NAMES utf8mb4;')
  push('SET FOREIGN_KEY_CHECKS = 0;')
  push('')

  /* ---------------------------------------------------------------- admins -- */
  push('-- Administrator (demo credential from Phase 1: info@safehomenetwork.com / Sa123456)')
  push('-- CHANGE THIS PASSWORD IMMEDIATELY AFTER INSTALLATION (see docs/INSTALL.md).')
  push(`INSERT INTO \`admins\` (\`id\`, \`name\`, \`email\`, \`password_hash\`, \`role\`, \`status\`) VALUES
  (1, 'Safe Home Network Owner', 'info@safehomenetwork.com', '$2y$12$O.mAyi0e.szDnNHbiL.sZ.Q4k66zoaUBJUNwBtn0.LJ9MSo/5IMoC', 'owner', 'active');`)
  push('')

  /* ------------------------------------------------------------ categories -- */
  push('-- Service categories (exactly the five used by the website)')
  data.categories.forEach((category, index) => {
    push(
      `INSERT INTO \`service_categories\` (\`id\`, \`name\`, \`description\`, \`sort_order\`) VALUES (${q(category.id)}, ${q(category.name)}, ${q(category.description)}, ${index + 1});`,
    )
  })
  push('')

  /* ---------------------------------------------------------------- niches -- */
  push('-- Niches (admin grouping; no public URL impact)')
  data.niches.forEach((niche, index) => {
    push(
      `INSERT INTO \`niches\` (\`id\`, \`slug\`, \`name\`, \`description\`, \`tone\`, \`status\`, \`sort_order\`) VALUES (${index + 1}, ${q(niche.slug)}, ${q(niche.name)}, ${q(niche.description)}, ${q(niche.tone)}, ${q(niche.status)}, ${index + 1});`,
    )
  })
  push('')

  /* ---------------------------------------------------------- phone groups -- */
  push('-- Phone directory groups (10)')
  data.groups.forEach((group) => {
    const directory = data.directory.find((entry) => entry.groupId === group.id)
    push(
      `INSERT INTO \`phone_groups\` (\`id\`, \`name\`, \`label\`, \`blurb\`, \`icon\`) VALUES (${q(group.id)}, ${q(group.name)}, ${q(directory?.label ?? `${group.name} services`)}, ${q(directory?.blurb ?? '')}, ${q(directory?.icon ?? 'Phone')});`,
    )
  })
  push('')

  /* --------------------------------------------------------- phone numbers -- */
  push('-- Tracking numbers (20, owner-confirmed 2026-11-07, nationwide)')
  data.groups.forEach((group) => {
    group.numbers.forEach((phone) => {
      const campaign = phone.campaign ?? {}
      push(
        `INSERT INTO \`phone_numbers\` (\`external_id\`, \`group_id\`, \`number\`, \`label\`, \`priority\`, \`status\`, \`network\`, \`campaign\`, \`campaign_nationwide\`, \`campaign_states\`, \`campaign_zip_codes\`, \`notes\`, \`verified_at\`) VALUES (${q(phone.id)}, ${q(group.id)}, ${q(phone.number)}, ${q(`${group.name} — ${phone.priority === 1 ? 'primary' : 'alternate'} line`)}, ${phone.priority}, ${q(phone.status)}, ${q(campaign.network ?? 'Owner-confirmed direct line')}, ${q(campaign.campaign ?? 'Nationwide (confirmed 2026-11-07)')}, ${campaign.nationwide ? 1 : 0}, ${json(campaign.states ?? null)}, ${json(campaign.zipCodes ?? null)}, ${q(campaign.notes ?? '')}, ${phone.status === 'active' ? iso('2026-11-07T09:00:00Z') : 'NULL'});`,
      )
    })
  })
  push('')

  /* ------------------------------------------------------------- services -- */
  push('-- Services (15) with their full page content and metadata')
  data.services.forEach((service, index) => {
    const nicheSlug = NICHE_BY_CATEGORY[service.category]
    const nicheId = data.niches.findIndex((niche) => niche.slug === nicheSlug) + 1
    push(
      `INSERT INTO \`services\` (\`slug\`, \`name\`, \`short_name\`, \`category_id\`, \`niche_id\`, \`icon\`, \`image\`, \`featured\`, \`status\`, \`sort_order\`, \`hero_headline\`, \`hero_subheadline\`, \`short_description\`, \`intro\`, \`common_needs\`, \`options\`, \`process_note\`, \`faqs\`, \`related\`, \`search_terms\`, \`meta_title\`, \`meta_description\`) VALUES (${q(service.slug)}, ${q(service.name)}, ${q(service.shortName ?? null)}, ${q(service.category)}, ${nicheId > 0 ? nicheId : 'NULL'}, ${q(service.icon)}, ${q(service.image)}, ${service.featured ? 1 : 0}, 'published', ${index + 1}, ${q(service.heroHeadline)}, ${q(service.heroSubheadline)}, ${q(service.shortDescription)}, ${json(service.intro)}, ${json(service.commonNeeds)}, ${json(service.options)}, ${q(service.processNote)}, ${json(service.faqs)}, ${json(service.related)}, ${json(service.searchTerms ?? null)}, ${q(service.metaTitle)}, ${q(service.metaDescription)});`,
    )
  })
  push('')

  /* --------------------------------------------------- service ↔ groups map -- */
  push('-- Service → phone group mapping (preserves the live website mapping)')
  data.services.forEach((service) => {
    const mapping = data.mapping[service.slug]
    if (!mapping) return
    mapping.groupIds.forEach((groupId, position) => {
      push(
        `INSERT INTO \`service_phone_groups\` (\`service_id\`, \`group_id\`, \`position\`) SELECT \`id\`, ${q(groupId)}, ${position + 1} FROM \`services\` WHERE \`slug\` = ${q(service.slug)};`,
      )
    })
  })
  push('')

  /* ---------------------------------------------------------------- pages -- */
  push('-- Pages')
  data.pages.forEach((page) => {
    const status = page.status === 'published' || page.status === 'scheduled' ? page.status : 'draft'
    push(
      `INSERT INTO \`pages\` (\`slug\`, \`title\`, \`template\`, \`status\`, \`excerpt\`, \`body\`, \`seo_title\`, \`seo_description\`, \`published_at\`, \`updated_by\`) VALUES (${q(page.slug)}, ${q(page.title)}, ${q(page.template)}, ${q(status)}, ${q(page.excerpt)}, NULL, ${q(page.seoTitle)}, ${q(page.seoDescription)}, ${status === 'draft' ? 'NULL' : iso(page.updatedAt)}, 1);`,
    )
  })
  push('')

  /* --------------------------------------------------------------- blogs --- */
  push('-- Blog categories, tags and posts')
  const categories = Array.from(new Set(data.posts.map((post) => post.category)))
  categories.forEach((name) => {
    push(
      `INSERT INTO \`blog_categories\` (\`slug\`, \`name\`, \`description\`) VALUES (${q(slugify(name))}, ${q(name)}, NULL);`,
    )
  })
  const tags = Array.from(new Set(data.posts.map((post) => slugify(post.category))))
  tags.forEach((tag) => {
    push(`INSERT INTO \`blog_tags\` (\`slug\`, \`name\`) VALUES (${q(tag)}, ${q(tag.replace(/-/g, ' '))});`)
  })
  data.posts.forEach((post) => {
    const status = post.status === 'scheduled' ? 'scheduled' : post.status === 'published' ? 'published' : 'draft'
    push(
      `INSERT INTO \`blog_posts\` (\`slug\`, \`title\`, \`category_id\`, \`status\`, \`excerpt\`, \`body\`, \`featured_image\`, \`featured_image_alt\`, \`seo_title\`, \`seo_description\`, \`author_name\`, \`published_at\`) VALUES (${q(post.slug)}, ${q(post.title)}, (SELECT \`id\` FROM \`blog_categories\` WHERE \`slug\` = ${q(slugify(post.category))} LIMIT 1), ${q(status)}, ${q(post.excerpt)}, NULL, ${q(post.featuredImage)}, ${q(post.title)}, ${q(post.seoTitle)}, ${q(post.seoDescription)}, ${q(post.author)}, ${status === 'draft' ? 'NULL' : iso(post.publishedAt)});`,
    )
  })
  data.posts.forEach((post) => {
    push(
      `INSERT INTO \`blog_post_tags\` (\`post_id\`, \`tag_id\`) SELECT p.\`id\`, t.\`id\` FROM \`blog_posts\` p, \`blog_tags\` t WHERE p.\`slug\` = ${q(post.slug)} AND t.\`slug\` = ${q(slugify(post.category))};`,
    )
  })
  push('')

  /* ------------------------------------------------------------ homepage --- */
  push('-- Homepage sections')
  data.sections.forEach((section) => {
    push(
      `INSERT INTO \`homepage_sections\` (\`section_key\`, \`name\`, \`heading\`, \`subheading\`, \`visible\`, \`sort_order\`) VALUES (${q(section.key)}, ${q(section.name)}, ${q(section.heading)}, ${q(section.subheading)}, ${section.visible ? 1 : 0}, ${section.sortOrder});`,
    )
  })
  push('')

  /* ----------------------------------------------------------------- faqs --- */
  push('-- FAQ groups and questions')
  push(`INSERT INTO \`faq_groups\` (\`id\`, \`name\`) VALUES ('home', 'Homepage FAQ'), ('how-it-works', 'How It Works FAQ');`)
  const faqRows = [
    ...data.faqs.home.map((faq, index) => ({ group: 'home', ...faq, index: index + 1 })),
    ...data.faqs.howItWorks.map((faq, index) => ({ group: 'how-it-works', ...faq, index: index + 1 })),
  ]
  faqRows.forEach((faq) => {
    push(
      `INSERT INTO \`faqs\` (\`group_id\`, \`question\`, \`answer\`, \`sort_order\`, \`visible\`) VALUES (${q(faq.group)}, ${q(faq.question)}, ${q(faq.answer)}, ${faq.index}, 1);`,
    )
  })
  push('')

  /* ------------------------------------------------------------- settings -- */
  push('-- Website settings (public ones are readable by the frontend)')
  const settings = [
    ['site_name', 'general', data.site.name, 'string', 1],
    ['site_short_name', 'general', data.site.shortName, 'string', 1],
    ['legal_name', 'general', data.site.legalName, 'string', 1],
    ['domain', 'general', data.site.domain, 'string', 1],
    ['site_url', 'general', data.site.url, 'string', 1],
    ['tagline', 'general', data.site.tagline, 'string', 1],
    ['description', 'general', data.site.description, 'text', 1],
    ['model_statement', 'general', data.site.modelStatement, 'text', 1],
    ['logo_path', 'appearance', '', 'string', 1],
    ['favicon_path', 'appearance', '/favicon.svg', 'string', 1],
    ['contact_phone', 'contact', data.site.contact.phone, 'string', 1],
    ['contact_phone_display', 'contact', data.site.contact.phoneDisplay, 'string', 1],
    ['contact_email', 'contact', data.site.contact.email, 'string', 1],
    ['support_hours', 'contact', data.site.contact.supportHours, 'string', 1],
    ['response_time', 'contact', data.site.contact.responseTime, 'string', 1],
    ['address_lines', 'contact', JSON.stringify(data.site.contact.addressLines), 'json', 1],
    ['social_facebook', 'social', data.site.social.facebook, 'string', 1],
    ['social_instagram', 'social', data.site.social.instagram, 'string', 1],
    ['social_linkedin', 'social', data.site.social.linkedin, 'string', 1],
    ['social_x', 'social', data.site.social.x, 'string', 1],
    ['social_youtube', 'social', data.site.social.youtube, 'string', 1],
    ['analytics_id', 'integrations', '', 'string', 0],
    ['google_verification', 'integrations', '', 'string', 0],
    ['header_scripts', 'integrations', '', 'script', 0],
    ['footer_scripts', 'integrations', '', 'script', 0],
    ['maintenance_mode', 'operations', '0', 'bool', 0],
    ['lead_notifications', 'operations', '1', 'bool', 0],
    ['call_tracking_enabled', 'operations', '1', 'bool', 0],
    ['lead_notification_email', 'operations', data.site.contact.email, 'string', 0],
    ['sitemap_enabled', 'seo', '1', 'bool', 1],
    ['timezone', 'general', 'America/New_York', 'string', 1],
    ['currency', 'general', 'USD', 'string', 1],
    ['api_version', 'general', 'v1', 'string', 0],
  ]
  settings.forEach(([key, group, value, type, isPublic]) => {
    push(
      `INSERT INTO \`settings\` (\`setting_key\`, \`setting_group\`, \`setting_value\`, \`setting_type\`, \`is_public\`, \`updated_by\`) VALUES (${q(key)}, ${q(group)}, ${q(value)}, ${q(type)}, ${isPublic}, 1);`,
    )
  })
  push('')

  /* ------------------------------------------------------------------ seo --- */
  push('-- Global SEO defaults')
  push(
    `INSERT INTO \`seo_settings\` (\`id\`, \`default_title\`, \`title_template\`, \`default_description\`, \`keywords\`, \`robots\`, \`sitemap_enabled\`, \`canonical_base\`, \`og_image\`, \`google_verification\`, \`analytics_id\`, \`updated_by\`) VALUES (1, ${q(data.site.seo.defaultTitle)}, ${q(data.site.seo.titleTemplate)}, ${q(data.site.seo.defaultDescription)}, ${json(['home services', 'call a contractor', 'roofing', 'plumbing', 'hvac', 'electrical'])}, 'index,follow', 1, ${q(`https://${data.site.domain}`)}, ${q(data.site.seo.defaultImage)}, '', '', 1);`,
  )
  push('')
  push('SET FOREIGN_KEY_CHECKS = 1;')
  push('')

  return lines.join('\n')
}

const main = async () => {
  const data = await loadFrontendData()
  const seed = buildSeed(data)
  const schemaPath = resolve(root, 'api/database/schema.sql')
  const schema = readFileSync(schemaPath, 'utf8')

  writeFileSync(resolve(root, 'api/database/seed.sql'), seed, 'utf8')
  writeFileSync(
    resolve(root, 'api/database/safehomenetwork.sql'),
    `${schema}\n\n-- ============================================================================\n--  SEED DATA\n-- ============================================================================\n\n${seed.replace(/^-- -+\n-- SEED[\s\S]*?\n-- -+\n\n/, '')}`,
    'utf8',
  )

  const counts = {
    categories: data.categories.length,
    services: data.services.length,
    groups: data.groups.length,
    numbers: data.groups.reduce((total, group) => total + group.numbers.length, 0),
    pages: data.pages.length,
    posts: data.posts.length,
    sections: data.sections.length,
    faqs: data.faqs.home.length + data.faqs.howItWorks.length,
  }
  console.log('API seed written:', JSON.stringify(counts))
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
