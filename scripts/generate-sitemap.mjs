/**
 * Generates public/sitemap.xml from the service directory plus the static routes.
 * Runs automatically via the `prebuild` npm script so the sitemap never drifts
 * from the configured services.
 *
 *   npm run sitemap
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const SITE_URL = 'https://safehomenetwork.com'

const STATIC_ROUTES = [
  { path: '/', priority: '1.0', changefreq: 'weekly' },
  { path: '/services', priority: '0.9', changefreq: 'weekly' },
  { path: '/blog', priority: '0.8', changefreq: 'weekly' },
  { path: '/how-it-works', priority: '0.8', changefreq: 'monthly' },
  { path: '/about', priority: '0.7', changefreq: 'monthly' },
  { path: '/contact', priority: '0.7', changefreq: 'yearly' },
  { path: '/service-area', priority: '0.7', changefreq: 'monthly' },
  { path: '/privacy-policy', priority: '0.3', changefreq: 'yearly' },
  { path: '/terms-and-conditions', priority: '0.3', changefreq: 'yearly' },
  { path: '/disclaimer', priority: '0.3', changefreq: 'yearly' },
  { path: '/do-not-sell-or-share', priority: '0.3', changefreq: 'yearly' },
  { path: '/accessibility', priority: '0.3', changefreq: 'yearly' },
]

const servicesSource = readFileSync(resolve(root, 'src/config/services.ts'), 'utf8')
const slugs = [...servicesSource.matchAll(/^\s{4}slug: '([a-z0-9-]+)',$/gm)].map((match) => match[1])

if (slugs.length === 0) {
  console.error('No service slugs found — aborting so the sitemap is never published empty.')
  process.exit(1)
}

/**
 * Blog categories ship with the app, so they belong in the static sitemap too.
 * Posts themselves are published over time by the scheduler, so they are added
 * at runtime by api/services/SitemapBuilder.php instead of being frozen here.
 */
let blogCategories = []
try {
  const contentDir = resolve(root, 'api/database/content/articles')
  const seen = new Set()
  for (const file of readdirSync(contentDir).filter((name) => name.endsWith('.json')).sort()) {
    for (const article of JSON.parse(readFileSync(resolve(contentDir, file), 'utf8'))) {
      const category = article.category?.slug
      if (category && !seen.has(category)) {
        seen.add(category)
        blogCategories.push(category)
      }
    }
  }
} catch {
  console.warn('Blog categories unavailable — static sitemap will omit /blog/category/*.')
}

const today = new Date().toISOString().slice(0, 10)

const urls = [
  ...STATIC_ROUTES.map(
    (route) => `  <url>
    <loc>${SITE_URL}${route.path}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${route.changefreq}</changefreq>
    <priority>${route.priority}</priority>
  </url>`,
  ),
  ...slugs.map(
    (slug) => `  <url>
    <loc>${SITE_URL}/services/${slug}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>0.8</priority>
  </url>`,
  ),
  ...blogCategories.map(
    (slug) => `  <url>
    <loc>${SITE_URL}/blog/category/${slug}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>weekly</changefreq>
    <priority>0.6</priority>
  </url>`,
  ),
].join('\n')

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-sitemap.mjs — do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`

writeFileSync(resolve(root, 'public/sitemap.xml'), xml)
console.log(`sitemap.xml written with ${STATIC_ROUTES.length + slugs.length} URLs (${slugs.length} services).`)
