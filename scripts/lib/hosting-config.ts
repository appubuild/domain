/**
 * Pure builders for the generated hosting configuration.
 *
 * Kept apart from the CLI in `scripts/emit-hosting-config.ts` so the policy can be unit-tested
 * without fetching anything or writing files.
 */

export type RedirectRow = {
  source_path: string;
  target_path: string;
  status_code: number;
  enabled: boolean;
};

/** AdSense needs far more origins than the one script the loader injects. */
const AD_SCRIPT_ORIGINS = [
  "https://pagead2.googlesyndication.com",
  "https://partner.googleadservices.com",
  "https://tpc.googlesyndication.com",
  "https://www.googletagservices.com",
  "https://adservice.google.com",
  "https://fundingchoicesmessages.google.com",
];
const AD_FRAME_ORIGINS = [
  "https://googleads.g.doubleclick.net",
  "https://tpc.googlesyndication.com",
  "https://www.google.com",
];
const AD_CONNECT_ORIGINS = [
  "https://pagead2.googlesyndication.com",
  "https://googleads.g.doubleclick.net",
  "https://ep1.adtrafficquality.google",
  "https://ep2.adtrafficquality.google",
];

/**
 * Build the policy. Deliberate choices, all of them documented in docs/security.md:
 *
 *  - `'unsafe-inline'` in script-src is unavoidable in a static export: Next inlines its
 *    hydration bootstrap into every page, and a nonce needs a server. Everything else is
 *    locked down, and `script-src-attr 'none'` still blocks inline event handlers.
 *  - connect-src names the Supabase host because that is the only API this site calls.
 */
export function buildCsp(options: { supabaseUrl: string | null; appUrl: string | null; ads: boolean }): string {
  const supabaseOrigin = (() => {
    if (!options.supabaseUrl) return null;
    try {
      return new URL(options.supabaseUrl).origin;
    } catch {
      return null;
    }
  })();

  const script = ["'self'", "'unsafe-inline'", ...(options.ads ? AD_SCRIPT_ORIGINS : [])];
  const connect = ["'self'", ...(supabaseOrigin ? [supabaseOrigin, supabaseOrigin.replace(/^https:/, "wss:")] : []), ...(options.ads ? AD_CONNECT_ORIGINS : [])];
  const frame = options.ads ? AD_FRAME_ORIGINS : [];
  const img = ["'self'", "data:", "blob:", ...(options.ads ? ["https:"] : [])];

  const directives: [string, string[] | null][] = [
    ["default-src", ["'self'"]],
    ["script-src", script],
    ["script-src-attr", ["'none'"]],
    ["style-src", ["'self'", "'unsafe-inline'"]],
    ["img-src", img],
    ["font-src", ["'self'"]],
    ["connect-src", connect],
    ["frame-src", frame],
    ["media-src", ["'self'"]],
    ["object-src", ["'none'"]],
    ["base-uri", ["'self'"]],
    ["form-action", ["'self'"]],
    ["frame-ancestors", ["'self'"]],
    ["manifest-src", ["'self'"]],
    ["worker-src", ["'self'", "blob:"]],
    ["upgrade-insecure-requests", null],
  ];

  return directives
    .filter(([, values]) => values === null || values.length > 0)
    .map(([name, values]) => (values === null ? name : `${name} ${values.join(" ")}`))
    .join("; ");
}

export function securityHeaders(csp: string, appUrl: string | null): [string, string][] {
  const headers: [string, string][] = [
    ["Content-Security-Policy", csp],
    ["X-Content-Type-Options", "nosniff"],
    ["X-Frame-Options", "SAMEORIGIN"],
    ["Referrer-Policy", "strict-origin-when-cross-origin"],
    ["Permissions-Policy", "camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()"],
    ["Cross-Origin-Opener-Policy", "same-origin"],
    ["Cross-Origin-Resource-Policy", "same-origin"],
  ];
  if (appUrl?.startsWith("https://")) {
    headers.push(["Strict-Transport-Security", "max-age=31536000; includeSubDomains"]);
  }
  return headers;
}

export function apacheConfig(rows: RedirectRow[], appUrl: string | null, csp: string): string {
  const lines: string[] = [];
  lines.push("# Generated by scripts/emit-hosting-config.ts — edits here are overwritten on build.");
  lines.push("");
  lines.push("<IfModule mod_rewrite.c>");
  lines.push("  RewriteEngine On");

  if (appUrl && appUrl.startsWith("https://")) {
    const host = new URL(appUrl).host;
    lines.push("  # canonical host + protocol");
    lines.push("  RewriteCond %{HTTPS} off [OR]");
    lines.push(`  RewriteCond %{HTTP_HOST} !^${host.replace(/\./g, "\\.")}$ [NC]`);
    lines.push(`  RewriteRule ^ https://${host}%{REQUEST_URI} [R=301,L]`);
  }

  for (const row of rows) {
    const flag = row.status_code === 301 || row.status_code === 308 ? "R=301,L" : "R=302,L";
    lines.push(`  RewriteRule ^${row.source_path.replace(/^\//, "").replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}/?$ ${row.target_path} [${flag}]`);
  }
  lines.push("</IfModule>");
  lines.push("");

  lines.push("# Security headers. Apache 2.4 / LiteSpeed; silently skipped if mod_headers is absent.");
  lines.push("<IfModule mod_headers.c>");
  for (const [name, value] of securityHeaders(csp, appUrl)) {
    lines.push(`  Header always set ${name} "${value.replace(/"/g, "'")}"`);
  }
  lines.push("  # Next emits content-hashed immutable assets; everything else revalidates.");
  lines.push('  <FilesMatch \"-[0-9a-f]{16}\\.(js|css)$\">');
  lines.push('    Header set Cache-Control "public, max-age=31536000, immutable"');
  lines.push("  </FilesMatch>");
  lines.push('  <FilesMatch \"\\.(html|json|txt|xml)$\">');
  lines.push('    Header set Cache-Control "public, max-age=0, must-revalidate"');
  lines.push("  </FilesMatch>");
  lines.push('  <FilesMatch \"\\.(woff2?|png|jpe?g|gif|svg|webp|avif|ico)$\">');
  lines.push('    Header set Cache-Control "public, max-age=86400"');
  lines.push("  </FilesMatch>");
  lines.push("</IfModule>");
  lines.push("");

  lines.push("# Compression, when the host offers mod_deflate.");
  lines.push("<IfModule mod_deflate.c>");
  lines.push("  AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/xml");
  lines.push("  AddOutputFilterByType DEFLATE application/javascript text/javascript application/json");
  lines.push("  AddOutputFilterByType DEFLATE image/svg+xml application/manifest+json");
  lines.push("</IfModule>");
  lines.push("");

  lines.push("ErrorDocument 404 /404.html");
  lines.push("DirectoryIndex index.html");
  lines.push("Options -Indexes");
  return lines.join("\n") + "\n";
}

export function netlifyHeaders(csp: string, appUrl: string | null): string {
  const lines: string[] = ["# Generated by scripts/emit-hosting-config.ts — edits here are overwritten on build.", "", "/*"];
  for (const [name, value] of securityHeaders(csp, appUrl)) {
    lines.push(`  ${name}: ${value}`);
  }
  lines.push('  Cache-Control: public, max-age=0, must-revalidate');
  lines.push("");
  lines.push("/_next/static/*");
  lines.push("  Cache-Control: public, max-age=31536000, immutable");
  return lines.join("\n") + "\n";
}

export function netlifyRedirects(rows: RedirectRow[]): string {
  const header = "# Generated by scripts/emit-hosting-config.ts — edits here are overwritten on build.\n";
  if (rows.length === 0) return header;
  return header + rows.map((row) => `${row.source_path}  ${row.target_path}  ${row.status_code}`).join("\n") + "\n";
}

